print(2+3*5)  # Demonstrates order of operations (multiplication before addition)
print(10/3)  # Shows float division result (returns 3.333...)
print(10//3)  # Shows integer division result (returns 3)
print(2**3)  # Demonstrates exponentiation (2 cubed = 8)
print(2**0.5)  # Calculates square root of 2 (≈1.414)
print(round(2.675635634654654, 2))  # Demonstrates rounding to 2 decimal places (2.68)
print(2**3/2*6-4*(3-4/2))  # Complex calculation following BODMAS rules
# Output: 20

