# This file demonstrates basic variable assignment and printing in Python

# Initialize a variable named 'number1' with the value 2
number1 = 2

# Print the current value of 'number1' (which is 2)
print(number1)

# Update the value of 'number1' to 3
number1 = 3

# Print the updated value of 'number1' (now 3)
print(number1)

