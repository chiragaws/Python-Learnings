# Escape Sequences
# \' - Single Quote
# \" - Double Quote
# \\ - Backslash
# \n - New Line
# \t - Tab
# \b - Backspace

# Printing a string with escaped double quotes
print ("Hello \"World!\" Dunia")
# Printing a string with escaped single quote
print ('I\'m learning Python programming.')
# Printing a string with escaped backslash
print ("This is a string with a backslash: \\")
# Printing a string with escaped new line character
print ("This is a string with a new line:\nHello!")
# Printing a string with escaped tab character
print ("This is a string with a tab:\tHello!")
# Printing a string with escaped backspace character
print ("This is a string with a backspace: Hello\bWorld!")